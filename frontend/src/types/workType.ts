/**
 * Представляет вид (тип) выполняемой работы.
 */
export interface WorkType {
  /** Уникальный идентификатор вида работы (UUID) */
  id: string;
  /** Название вида работы (например, "Укладка кирпича") */
  title: string;
  /** Единица измерения объема работы (например, "м²", "м³") */
  unit: string;
}
