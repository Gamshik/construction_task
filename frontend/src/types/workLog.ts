import { WorkType } from './workType';

/**
 * Представляет запись в журнале работ (лог работы).
 */
export interface WorkLog {
  /** Уникальный идентификатор записи (UUID) */
  id: string;
  /** Дата выполнения работы в формате ISO строки */
  date: string;
  /** Идентификатор связанного вида работы */
  workTypeId: string;
  /** Связанный объект вида работы или null, если не найден */
  workType: WorkType | null;
  /** Объем выполненных работ в соответствующих единицах измерения */
  volume: number;
  /** ФИО исполнителя (бригадира или рабочего) */
  executorName: string;
}

/**
 * Направление сортировки ("asc" - по возрастанию, "desc" - по убыванию).
 */
export type SortOrder = 'asc' | 'desc';

/**
 * Параметры фильтрации и пагинации списка логов работ.
 */
export interface WorkLogFilterParams {
  /** Количество записей на страницу */
  limit: number;
  /** Поисковый запрос для фильтрации по ФИО исполнителя или названию работы */
  search?: string;
  /** Начальная дата для фильтрации по диапазону дат */
  startDate?: string;
  /** Конечная дата для фильтрации по диапазону дат */
  endDate?: string;
  /** Направление сортировки по дате выполнения */
  sort?: SortOrder;
}

/**
 * Пагинированный ответ со списком логов работ и мета-данными.
 */
export interface PaginatedWorkLogs {
  /** Массив логов работ на текущей странице */
  data: WorkLog[];
  /** Мета-данные пагинации */
  meta: {
    /** Общее количество записей, удовлетворяющих фильтру */
    total: number;
    /** Номер текущей страницы */
    page: number;
    /** Лимит записей на странице */
    limit: number;
    /** Общее количество страниц */
    totalPages: number;
  };
}

/**
 * Входные данные для создания новой записи в журнале работ.
 */
export interface CreateWorkLogInput {
  /** Дата выполнения работы в формате ISO */
  date: string;
  /** Идентификатор выбранного вида работы */
  workTypeId: string;
  /** Объем выполненной работы */
  volume: number;
  /** ФИО исполнителя */
  executorName: string;
}

/**
 * Входные данные для обновления существующей записи в журнале работ.
 */
export interface UpdateWorkLogInput extends CreateWorkLogInput {
  /** Уникальный идентификатор обновляемой записи */
  id: string;
}
