import { WorkLog } from '@domain/WorkLog.entity';

/**
 * Опции фильтрации и пагинации для получения записей журнала работ.
 */
export interface WorkLogFilterOptions {
  /** Номер текущей страницы (для пагинации) */
  page?: number;
  /** Количество записей на странице (для пагинации) */
  limit?: number;
  /** Поисковый запрос (фильтрация по имени исполнителя или названию типа работ) */
  search?: string;
  /** Начальная дата диапазона выполнения работ */
  startDate?: Date;
  /** Конечная дата диапазона выполнения работ */
  endDate?: Date;
  /** Направление сортировки по дате и времени создания (asc - по возрастанию, desc - по убыванию) */
  sort?: 'asc' | 'desc';
}

/**
 * Интерфейс (выходной порт) репозитория для управления сущностями WorkLog.
 * Описывает контракт для работы с хранилищем данных.
 */
export interface WorkLogRepositoryPort {
  /**
   * Находит все записи с учетом параметров фильтрации и пагинации.
   * 
   * @param options - Параметры фильтрации и пагинации
   * @returns Объект, содержащий список найденных записей и их общее количество
   */
  findAll(options?: WorkLogFilterOptions): Promise<{ workLogs: WorkLog[]; total: number }>;

  /**
   * Находит одну запись по её идентификатору.
   * 
   * @param id - Идентификатор записи
   * @returns Найденая сущность или null, если запись не найдена
   */
  findById(id: string): Promise<WorkLog | null>;

  /**
   * Сохраняет новую запись в хранилище данных.
   * 
   * @param workLog - Сущность для сохранения
   * @returns Сохраненная сущность с заполненными системными полями
   */
  create(workLog: WorkLog): Promise<WorkLog>;

  /**
   * Обновляет существующую запись в хранилище данных.
   * 
   * @param workLog - Сущность с обновленными данными
   * @returns Обновленная сущность
   */
  update(workLog: WorkLog): Promise<WorkLog>;

  /**
   * Удаляет запись из хранилища данных.
   * 
   * @param id - Идентификатор удаляемой записи
   */
  delete(id: string): Promise<void>;
}

